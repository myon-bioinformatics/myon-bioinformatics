#!/usr/bin/env python3
"""Evidence layer of the fleet graph: what tests, produces, observes or supports what, and which record says so.

Owned by the parent (AGENTS.md: fleet tooling lives here only); ``vendor_fleet_plan`` imports it. It reads the
records the repositories already keep — vendor locks, generator markers, browser evidence receipts
(btk-evidence-gif/*), the JUnit failure corpus, proposition ledgers, input bundles, provenance JSON, the
parent's audit snapshot — and never rewrites them. Spec: docs/fleet-records.md.

Every relation is an edge from what is depended on (``source``) to what must be rechecked when it changes
(``target``), so one breadth-first walk answers "what does this change reach" and the reverse walk answers
"what is this judgement based on". Each edge carries:

  lock         the record asserting it ("Repo:path"), or the snapshot it came from
  basis        observed (read from a record or the tree) | derived (a fixed rule over records) | hypothesis
  method       how it was found: lock-file, ast-import, text-mention, workflow, locked_ci, generator-marker,
               sha256, ledger, receipt, receipt-url, junit-corpus, audit-snapshot
  compare      match | different | unknown: a recorded version or hash against the current tree. A difference is
               never called old, incompatible or "must update"; compatibility is judged by tests.
  state        not_collected | running | success | failure | not_applicable | unverifiable | pending
  observed_at  the time the record itself states (not the time of this run), when it states one

Several observations of one subject stay separate (a retry never replaces the first failure; a newer ledger row
never removes an older counterexample). Output is sorted and capped (LIMIT); what the cap leaves out is counted.
"""
