def short(name):
    name = str(name).strip().removeprefix("https://github.com/").removesuffix(".git").strip("/")
    return name.split("/", 1)[1] if name.startswith(OWNER + "/") else name


def split(node):
    repo, _, path = node.partition(":")
    return repo, path


def sha256(data):
    return hashlib.sha256(data).hexdigest()


class Relations:
    """Collected edges, findings and per-repository coverage, deduplicated and capped deterministically."""

    def __init__(self, limit=LIMIT):
        self.edges, self.findings, self.coverage, self.limit = [], [], {}, limit

    def add(self, kind, source, target, lock, *, method, basis="observed", **extra):
        self.edges.append({"kind": kind, "source": source, "target": target, "lock": lock, "basis": basis,
                           "method": method, **{k: v for k, v in extra.items() if v is not None}})

    def finding(self, repo, kind, subject, detail):
        self.findings.append({"repository": repo, "kind": kind, "subject": subject, "detail": detail})

    def cover(self, repo, key, value):
        self.coverage.setdefault(repo, {})[key] = value

    def result(self):
        unique, seen = [], {}
        for e in sorted(self.edges, key=lambda e: (e["kind"], e["target"], e["source"], e["lock"], e["method"],
                                                   str(e.get("pin")), str(e.get("observed_at")))):
            # Observations at different commits or times are separate statements, never one overwriting another.
            key = (e["kind"], e["target"], e["source"], e["lock"], e.get("pin"), e.get("observed_at"))
            text = json.dumps(e, sort_keys=True, ensure_ascii=False)
            if key in seen:
                if seen[key] != text:  # one identifier, two contents: report, keep the first
                    self.finding(split(e["target"])[0], "duplicate-id", f"{e['kind']}:{e['target']}",
                                 f"{e['lock']} states {e['kind']} {e['source']} → {e['target']} twice with different values")
                continue
            seen[key] = text
            unique.append(e)
        kept = unique[:self.limit]
        kinds = {}
        for e in kept:
            kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
        findings = {(f["kind"], f["repository"], f["subject"]): f for f in self.findings}
        return {"relations": kept, "kinds": dict(sorted(kinds.items())), "dropped": len(unique) - len(kept),
                "findings": [findings[k] for k in sorted(findings)], "coverage": dict(sorted(self.coverage.items())),
                "cycles": relation_cycles(kept)}


def canonical_names(discovery):
    """{old or current short name: current name} from the hubs' previous_names (identity follows repository_id)."""
    names = {}
    for r in discovery["repositories"]:
        names[r["repository"]] = r["repository"]
        for old in r.get("previous_names") or []:
            names.setdefault(short(old), r["repository"])
    return names


def _record_kind(path):
    parts = path.split("/")
    if SKIP & set(parts[:-1]) or (("fixtures" in parts[:-1] or "tests" in parts[:1]) and not path.endswith("classification.json")):
        return False
    return any(fnmatch.fnmatch(path, p) for p in RECORD_PATTERNS)


def _is_test(path):
    parts = path.split("/")
    return (not SKIP & set(parts[:-1]) and "fixtures" not in parts[:-1]
            and any(fnmatch.fnmatch(parts[-1], p) for p in TEST_PATTERNS)
            and (parts[-1].endswith((".dart", ".js", ".mjs", ".cjs", ".ts")) or any(p in ("tests", "test") for p in parts[:-1])))


def _memo(fleet, key, compute):
    """The fleet's per-run cache when it has one: a second build of the graph costs no git call."""
    memo = getattr(fleet, "_memo", None)
    return memo(("fleet_records",) + key, compute) if memo else compute()


def _local(fleet, repo):
    """Blobs are present without a network fetch (worktree or full clone), so wide reads stay cheap."""
    check = getattr(fleet, "blobs_local", None)
    return True if check is None else check(repo)


def _modules(path):
    """Import names a Python file can be reached under: 'errlib/junit.py' → errlib.junit, junit."""
    if not path.endswith(".py"):
        return set()
    parts = list(PurePosixPath(path).with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    names = {".".join(parts[i:]) for i in range(len(parts)) if parts[i:]}
    return {n for n in names if n and n != "src"}


def _imports(text):
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return set()
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names |= {a.name for a in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            names.add(node.module)
            names |= {f"{node.module}.{a.name}" for a in node.names}
        elif isinstance(node, ast.Call) and getattr(node.func, "attr", getattr(node.func, "id", "")) in ("import_module", "_sibling"):
            if node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                names.add(node.args[0].value)
    return names


def tests_for(fleet, repo, rev, paths):
    """[(path, test_or_workflow, method)] — ast-import > workflow > text-mention; nothing found means unregistered."""
    files = fleet.files(repo, rev)
    tests = [p for p in sorted(files) if _is_test(p)]
    workflows = [p for p in sorted(files) if p.startswith(".github/workflows/") and p.endswith((".yml", ".yaml"))]
    fleet.prefetch(repo, rev, tests + workflows)
    texts = {p: (fleet.read(repo, rev, p) or b"").decode("utf-8", "replace") for p in tests + workflows}
    imported = {p: _imports(texts[p]) for p in tests if p.endswith(".py")}
    out = []
    for path in sorted(set(paths)):
        name = PurePosixPath(path).name
        mods = _modules(path)
        by_name = name not in GENERIC_NAMES and not name.startswith("LICENSE") and len(name) >= 6
        for test in tests:
            if test == path:
                continue
            if mods & imported.get(test, set()):
                out.append((path, test, "ast-import"))
            elif path in texts[test] or (by_name and re.search(r"(?<![\w.-])" + re.escape(name) + r"(?![\w-])", texts[test])):
                out.append((path, test, "text-mention"))
        for workflow in workflows:
            if path in texts[workflow]:
                out.append((path, workflow, "workflow"))
    return out


