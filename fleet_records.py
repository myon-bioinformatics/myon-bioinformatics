_INDEX = {}


def hash_index(fleet, repo, rev, directory, *, limit=2000):
    """{sha256: path} of the JSON/JSONL/TOML/CSV files under directory (local blobs only; memoised per run)."""
    key = (id(fleet), repo, rev, directory)
    if key not in _INDEX:
        files = [p for p in sorted(fleet.files(repo, rev)) if p.startswith(directory.rstrip("/") + "/")
                 and p.endswith((".json", ".jsonl", ".toml", ".csv", ".tsv"))][:limit]
        _INDEX[key] = {} if not _local(fleet, repo) else {sha256(fleet.read(repo, rev, p) or b""): p for p in reversed(files)}
    return _INDEX[key]


def _image_ok(data, path):
    """The bytes are the image format the name says: GIF89a/87a or PNG with an IHDR chunk."""
    if path.lower().endswith(".gif"):
        return data[:6] in (b"GIF89a", b"GIF87a") and len(data) > 13
    if path.lower().endswith(".png"):
        return data[:8] == b"\x89PNG\r\n\x1a\n" and data[12:16] == b"IHDR"
    return None


def receipt_layers(doc, data, current_commit=None):
    """Four separate checks of one browser evidence receipt, plus the commit it was recorded at.

    exists / digest / format / operation / visual are independent: a valid image of a failed run is still a
    failed operation, and nothing here can say the screens look as intended (visual stays not_collected).
    """
    layers = {"exists": "failure" if data is None else "success"}
    if data is None:
        layers.update(digest="unknown", format="not_collected")
    else:
        recorded = doc.get("sha256")
        layers["digest"] = ("unknown" if not recorded else
                            "match" if sha256(data) == recorded and doc.get("bytes") in (None, len(data)) else "different")
        ok = _image_ok(data, str(doc.get("gif") or doc.get("png") or ""))
        layers["format"] = "unverifiable" if ok is None else "success" if ok else "failure"
    shots = [s for s in doc.get("shots") or [] if isinstance(s, dict)]
    statuses = [s.get("status") for s in shots]
    layers["operation"] = ("not_collected" if not shots else "success" if all(s == "pass" for s in statuses) else "failure")
    summary = doc.get("summary") or {}
    if shots and summary and (summary.get("pass"), summary.get("fail")) != (statuses.count("pass"), len(statuses) - statuses.count("pass")):
        layers["operation"] = "failure"
        layers["summary_mismatch"] = True
    layers["visual"] = "not_collected"
    commit = doc.get("commit")
    layers["commit"] = ("unknown" if not commit or not current_commit or current_commit == "WORKTREE"
                        else "same" if commit == current_commit else "different")
    return layers


def _receipt(rel, fleet, repo, rev, path, doc, names, fleet_files):
    node = f"{repo}:{path}"
    base = PurePosixPath(path).parent
    image = doc.get("gif") or doc.get("png")
    image_path = str(base / image) if image else None
    files = fleet.files(repo, rev)
    data = fleet.read(repo, rev, image_path) if image_path and image_path in files else None
    layers = receipt_layers(doc, data, rev)
    if image_path is None or data is None:
        rel.finding(repo, "missing-evidence", path, f"{path} names {image_path or 'no image'}, which is not in the tree")
    else:
        rel.add("verified_by", f"{repo}:{image_path}", node, node, method="receipt", compare=layers["digest"],
                state=layers["format"], observed_at=doc.get("recorded"))
    seen = set()
    for shot in doc.get("shots") or []:
        url = str((shot or {}).get("url") or "").split("?")[0].split("#")[0].lstrip("/")
        match = [p for p in files if url and (p == url or p.endswith("/" + url))]
        if len(match) == 1 and match[0] not in seen:  # the page the shot opened, when the tree has exactly one
            seen.add(match[0])
            rel.add("derived_from", f"{repo}:{match[0]}", node, node, method="receipt-url", basis="derived",
                    state="success" if shot.get("status") == "pass" else "failure", observed_at=doc.get("recorded"))
    encoder = doc.get("encoder") or {}
    if encoder.get("web_ui") and HEX40.fullmatch(str(encoder["web_ui"])):
        words = str(encoder.get("module") or "").split()
        owner = names.get(words[0], words[0]) if words else "PySaiyanWeBoo"
        tool = next((w for w in words[1:] if "." in w), "")
        candidates = sorted(p for p in fleet_files(owner) if tool and PurePosixPath(p).name == tool and _is_shipped(p))
        source = f"{owner}:{candidates[0]}" if len(candidates) == 1 else f"{owner}:"
        rel.add("derived_from", source, node, node, method="receipt", basis="observed" if len(candidates) == 1 else "hypothesis",
                pin=encoder["web_ui"], observed_at=doc.get("recorded"))
    rel.cover(repo, "receipt:" + path, layers)
    return layers


def _is_shipped(path):
    parts = path.split("/")
    return not SKIP & set(parts[:-1]) and not {"tests", "test", "fixtures", "vendor"} & set(parts[:-1])


def _corpus(rel, fleet, repo, rev, path, items, names):
    """JUnit failure corpus: each case is its own observation of one run; equal messages are never merged."""
    lock = f"{repo}:{path}"
    base = PurePosixPath(path).parent
    files = fleet.files(repo, rev)
    entries = sorted((x for x in items if isinstance(x, dict) and x.get("id")), key=lambda x: str(x["id"]))
    counts = {"cases": len(entries), "read": 0, "found": 0, "not_found": 0, "hint": 0, "missing": 0}
    local = _local(fleet, repo)
    ids = {}
    for item in entries[:PER_RECORD]:
        ids[item["id"]] = ids.get(item["id"], 0) + 1
        origin = short(item.get("repo") or "")
        origin = names.get(origin, origin)
        run = f"{origin}:actions/runs/{item.get('run_id')}" + (f"/attempts/{item['attempt']}" if item.get("attempt") else "")
        xml = str(base / item["xml"]) if item.get("xml") else None
        if not xml or xml not in files:
            counts["missing"] += 1
            rel.finding(repo, "missing-reference", f"{path}#{item['id']}", f"{path}: case {item['id']} names {xml}, not in the tree")
            continue
        rel.add("observed_in", run, f"{repo}:{xml}", lock, method="junit-corpus", observed_at=item.get("date"),
                value={"artifact": item.get("artifact"), "job": item.get("job")})
        if item.get("golden"):
            golden = str(base / item["golden"])
            value = {"classification": item.get("classification")}
            if golden in files and local:
                lines = (fleet.read(repo, rev, golden) or b"").decode("utf-8", "replace").splitlines()
                # FOUND is an observation, NOT FOUND an absence that was looked for, HINT a candidate (hypothesis).
                value.update(found=sum(l.startswith("FOUND:") for l in lines),
                             not_found=sum(l.startswith("NOT FOUND:") for l in lines),
                             hint=sum(l.startswith("HINT:") for l in lines))
                counts["read"] += 1
                for key in ("found", "not_found", "hint"):
                    counts[key] += value[key]
            rel.add("derived_from", f"{repo}:{xml}", f"{repo}:{golden}", lock, method="junit-corpus", value=value,
                    state="success" if golden in files else "not_collected")
    for case, n in sorted(ids.items()):
        if n > 1:
            rel.finding(repo, "duplicate-id", f"{path}#{case}", f"{path}: case id {case} appears {n} times")
    counts["truncated"] = max(0, len(entries) - PER_RECORD)
    if not local:
        counts["goldens"] = "not_collected"
    rel.cover(repo, "corpus:" + path, counts)


def _toml_entries(data, table, key="id"):
    try:
        document = tomllib.loads((data or b"").decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError):
        return None
    return {str(x.get(key)): x for x in document.get(table) or [] if isinstance(x, dict) and x.get(key)}


def _ledger(rel, fleet, repo, rev, path, data):
    """Proposition ledger rows: judgement ← data (by sha256) and definition (TOML entry at code_version vs now)."""
    lock = f"{repo}:{path}"
    cycle = PurePosixPath(path).parent.parent
    files = fleet.files(repo, rev)
    definitions = f"{cycle}/propositions.toml"
    rows, bad = [], 0
    for line in (data or b"").decode("utf-8", "replace").splitlines():
        if line.strip():
            try:
                row = json.loads(line)
            except ValueError:
                bad += 1
                continue
            if isinstance(row, dict) and row.get("id") and row.get("recorded_at"):
                rows.append(row)
    history = {}
    for row in rows:
        history.setdefault(str(row["id"]), []).append(row)
    local = _local(fleet, repo)
    index = hash_index(fleet, repo, rev, str(cycle))
    now_entries = _toml_entries(fleet.read(repo, rev, definitions), "proposition") if definitions in files else None
    then_entries = {}
    counts = {"rows": len(rows), "propositions": len(history), "unreadable_lines": bad, "data_match": 0, "data_unresolved": 0,
              "definition": {"match": 0, "different": 0, "unknown": 0}, "with_counterexamples": 0}
    for pid in sorted(history)[:PER_RECORD]:
        rows_of = sorted(history[pid], key=lambda r: str(r["recorded_at"]))
        latest = rows_of[-1]
        forms = latest.get("forms") or {}
        verdict = (forms.get("original") or {}).get("verdict")
        judgement = f"{repo}:{path}#{pid}@{latest['recorded_at']}"
        kept = [{"at": r["recorded_at"], "verdict": ((r.get("forms") or {}).get("original") or {}).get("verdict"),
                 "counterexamples": ((r.get("forms") or {}).get("original") or {}).get("counterexamples")} for r in rows_of]
        counter_rows = sum(bool(k["counterexamples"]) for k in kept)
        counts["with_counterexamples"] += bool(counter_rows)
        value = {"verdict": verdict, "objection": latest.get("objection"), "rows": len(kept),
                 "rows_with_counterexamples": counter_rows, "history": kept[-HISTORY:]}
        found = index.get(latest.get("data_sha256"))
        if found:
            counts["data_match"] += 1
            rel.add("derived_from", f"{repo}:{found}", judgement, lock, method="sha256", compare="match",
                    sha256=latest.get("data_sha256"), observed_at=latest["recorded_at"])
        else:
            counts["data_unresolved"] += 1
            rel.add("derived_from", f"{repo}:{cycle}/", judgement, lock, method="sha256", compare="unknown",
                    state="not_collected" if not local else "unverifiable", sha256=latest.get("data_sha256"),
                    observed_at=latest["recorded_at"])
        code = latest.get("code_version")
        compare = "unknown"
        if now_entries is not None and pid in now_entries and code and HEX40.fullmatch(str(code)):
            if code not in then_entries:
                blob = fleet.blob_at(repo, code, definitions)
                then_entries[code] = _toml_entries(fleet.read_blob(repo, blob), "proposition") if blob else None
            then = then_entries[code]
            if then is not None:
                compare = "match" if then.get(pid) == now_entries[pid] else "different"
        counts["definition"][compare] += 1
        state = "pending" if verdict not in ("Supported", "Refuted", "Rejected") else "success"
        rel.add("derived_from", f"{repo}:{definitions}#{pid}", judgement, lock, method="ledger", compare=compare,
                pin=code, sha256=latest.get("definition_sha256"), state=state, value=value, observed_at=latest["recorded_at"])
        # The verdict is a statement about the proposition in this ledger ("ledger#P1"), not about its definition,
        # so definition → judgement → verdict stays acyclic and a new judgement is a new source, not an overwrite.
        if verdict == "Supported":
            rel.add("supports", judgement, f"{repo}:{path}#{pid}", lock, method="ledger", observed_at=latest["recorded_at"])
        elif verdict in ("Refuted", "Rejected"):
            rel.add("contradicts", judgement, f"{repo}:{path}#{pid}", lock, method="ledger", observed_at=latest["recorded_at"])
    counts["truncated"] = max(0, len(history) - PER_RECORD)
    if not local:
        counts["data_index"] = "not_collected"
    rel.cover(repo, "ledger:" + path, counts)


def _pins(rel, fleet, repo, rev, path, doc, tree):
    """Generic provenance: path→sha256 (or git_blob) pins against the current tree of the repository they name.

    tree(repo) gives (revision, files) of a readable repository or None. A pin naming no repository is looked up in
    the record's own repository; one that is nowhere in it (an installed package file, an export) stays unknown.
    """
    lock = f"{repo}:{path}"
    base = PurePosixPath(path).parent
    context = short(doc.get("repository")) if isinstance(doc.get("repository"), str) else None
    source_dir = doc.get("source") if isinstance(doc.get("source"), str) and "/" not in doc["source"].strip("/") else None
    found = {"pins": 0, "match": 0, "different": 0, "unknown": 0, "other_repositories": 0, "commits": {}}

    def resolve(owner, name):
        seen = tree(owner)
        if seen is None:
            return None, None
        _name, _rev, files, _commit = seen
        options = ([name] if owner != repo else
                   [str(base / name), str(base.parent / name)] + ([str(base.parent / source_dir / name)] if source_dir else []) + [name])
        return seen, next((o for o in options if o in files), None)

    def pin(item_repo, name, digest=None, blob=None, revision=None):
        if not isinstance(name, str) or not ((isinstance(digest, str) and HEX64.fullmatch(digest)) or
                                             (isinstance(blob, str) and HEX40.fullmatch(blob))):
            return
        found["pins"] += 1
        # An item naming its repository is looked up there only; otherwise the record's own directory first, then
        # the repository the record is about (top-level "repository").
        owners = [short(item_repo)] if isinstance(item_repo, str) else [repo] + ([context] if context and context != repo else [])
        for owner in owners:
            seen, where = resolve(owner, name)
            if where is not None:
                break
        owner = seen[0] if seen else owner  # a previous name resolves to the current one (repository_id)
        found["other_repositories"] += owner != repo
        method = "sha256" if not blob else "git-blob"
        if where is None and owner == repo and isinstance(digest, str):  # a logical name: find the file by its hash
            where = hash_index(fleet, repo, seen[1], str(base.parent)).get(digest) if seen else None
            method = "sha256-index"
        if where is None:
            found["unknown"] += 1
            if seen is not None and isinstance(item_repo, str):  # the item names the repository, whose tree lacks the path
                at = f" at {revision[:12]}" if isinstance(revision, str) and HEX40.fullmatch(revision) else ""
                rel.finding(repo, "pinned-path-gone" if at else "missing-reference", f"{path}#{owner}:{name}",
                            f"{path} pins {owner}:{name}{at}; the current tree has no such path"
                            + (" (moved or removed since: a recompute candidate, not an error of the record)" if at else ""))
            return
        current_rev = seen[1]
        if blob and isinstance(blob, str):
            compare = "match" if fleet.blob(owner, current_rev, where) == blob else "different"
        else:
            compare = "match" if sha256(fleet.read(owner, current_rev, where) or b"") == digest else "different"
        found[compare] += 1
        rel.add("derived_from", f"{owner}:{where}", lock, lock, method=method, basis="derived" if method == "sha256-index" else "observed",
                compare=compare,
                sha256=digest if isinstance(digest, str) else None, pin=revision if isinstance(revision, str) and HEX40.fullmatch(revision) else None)

    def walk(value, depth=0):
        if depth > 3:
            return
        if isinstance(value, dict):
            if isinstance(value.get("sha256"), dict):
                for name, digest in sorted(value["sha256"].items()):
                    pin(None, name, digest)
            if isinstance(value.get("path"), str) and (isinstance(value.get("sha256"), str) or isinstance(value.get("git_blob"), str)):
                pin(value.get("repository"), value["path"], value.get("sha256"), value.get("git_blob"),
                    value.get("revision") or value.get("commit") or doc.get("revision"))
            for key, item in sorted(value.items()):
                if isinstance(item, str) and COMMIT_KEY.search(key) and HEX40.fullmatch(item) and depth == 0:
                    owner = context or repo
                    seen = tree(owner)
                    current = seen[3] if seen else None
                    found["commits"][key] = {"repository": owner, "commit": item, "compare": "unknown" if current in (None, "WORKTREE")
                                             else "same" if item == current else "different"}
                elif isinstance(item, (dict, list)):
                    walk(item, depth + 1)
        elif isinstance(value, list):
            for item in value[:PER_RECORD]:
                walk(item, depth + 1)
    walk(doc)
    if found["pins"] or found["commits"]:
        rel.cover(repo, "record:" + path, found)


def _generator_path(token, path, files):
    token = token.strip("`'\" ")
    if token.startswith(("python -m ", "python3 -m ")):
        module = token.split()[-1].replace(".", "/")
        options = (f"{module}.py", f"src/{module}.py", f"{module}/__main__.py", f"src/{module}/__main__.py")
    else:
        options = (token, str(PurePosixPath(path).parent / token))
    return next((o for o in options if o in files), None)


def _generated(rel, fleet, repo, rev, files):
    """produced_by from 'Generated by <tool>' markers in the first lines and *.generated.json "source"/"generator"."""
    if not _local(fleet, repo):
        rel.cover(repo, "generated", "not_collected")
        return set()
    location = fleet.location(repo)
    target = [] if rev == "WORKTREE" else [rev]
    done = _memo(fleet, ("grep", repo, rev), lambda: fleet.run(
        location, "grep", "-n", "-I", "-i", "-E", "--max-count", "3", "^.{0,8}" + MARKER, *target, "--",
        ":!*.lock", ":!**/node_modules/**", ":!**/fixtures/**", ":!uv.lock", ":!**/vendor/**"))
    produced = set()
    for line in done.stdout.decode("utf-8", "replace").splitlines():
        if target and line.startswith(rev + ":"):
            line = line[len(rev) + 1:]
        path, _, rest = line.partition(":")
        number, _, text = rest.partition(":")
        if not number.isdigit() or int(number) > 5 or path not in files:
            continue
        match = GENERATOR.search(text)
        if not match:
            continue
        generator = _generator_path(match.group(1), path, files)
        if generator is None:
            rel.finding(repo, "generator-missing", path, f"{path}:{number} names {match.group(1)}, which is not in the tree")
            continue
        produced.add(path)
        rel.add("produced_by", f"{repo}:{generator}", f"{repo}:{path}", f"{repo}:{path}", method="generator-marker",
                line=int(number))
    for path in sorted(p for p in files if p.endswith(".generated.json") and _is_shipped(p)):
        try:
            doc = json.loads(fleet.read(repo, rev, path) or b"{}")
        except ValueError:
            continue
        token = next((str(doc[k]) for k in ("generator", "generated_by", "source") if isinstance(doc, dict) and doc.get(k)), "")
        module = token.split()[0] if token else ""
        parts = module.split(".")
        generator = next((_generator_path("python -m " + ".".join(parts[:i]), path, files) for i in range(len(parts), 0, -1)
                          if _generator_path("python -m " + ".".join(parts[:i]), path, files)), None)
        if generator:
            produced.add(path)
            rel.add("produced_by", f"{repo}:{generator}", f"{repo}:{path}", f"{repo}:{path}", method="generator-marker",
                    value={"source": token})
    rel.cover(repo, "generated", len(produced))
    return produced


def collect(fleet, discovery, edges, *, registry=None, snapshot=None, limit=LIMIT):
    """All relations the readable repositories' own records support, plus tested_by for the files they reach."""
    rel = Relations(limit)
    names = canonical_names(discovery)
    readable = {r["repository"]: r for r in discovery["repositories"] if r["category"] in ("target", "insufficient") and r["revision"]}

    def files_of(repo):
        r = readable.get(repo)
        return fleet.files(repo, r["revision"]) if r else {}

    def tree(repo):
        r = readable.get(names.get(repo, repo))
        return (r["repository"], r["revision"], fleet.files(r["repository"], r["revision"]), commit_of(r)) if r else None

    def commit_of(r):  # the parent's working tree compares as its HEAD commit
        if r["revision"] != "WORKTREE":
            return r["revision"]
        done = _memo(fleet, ("head", r["repository"]), lambda: fleet.run(fleet.location(r["repository"]), "rev-parse", "--verify", "-q", "HEAD"))
        return done.stdout.decode().strip() or None if done.returncode == 0 else None
    copies = {}
    for e in edges:  # copies whose behaviour a test can exercise (a license text has none)
        if e["kind"] in ("vendor", "launcher"):
            repo, path = split(e["target"])
            copies.setdefault(repo, set()).add(path)
    for repo, r in sorted(readable.items()):
        rev = r["revision"]
        files = fleet.files(repo, rev)
        records = [p for p in sorted(files) if _record_kind(p)]
        fleet.prefetch(repo, rev, records)
        subjects = set(copies.get(repo, ()))
        for path in records:
            data = fleet.read(repo, rev, path)
            if path.endswith(".jsonl"):
                _ledger(rel, fleet, repo, rev, path, data)
                continue
            try:
                doc = json.loads(data or b"null")
            except ValueError:
                rel.finding(repo, "record-unreadable", path, f"{path}: not JSON")
                continue
            if isinstance(doc, dict) and str(doc.get("schema", "")).startswith("btk-evidence"):
                _receipt(rel, fleet, repo, rev, path, doc, names, files_of)
            elif isinstance(doc, list) and doc and isinstance(doc[0], dict) and {"run_id", "xml"} <= set(doc[0]):
                _corpus(rel, fleet, repo, rev, path, doc, names)
            elif isinstance(doc, dict):
                _pins(rel, fleet, repo, rev, path, doc, tree)
        _generated(rel, fleet, repo, rev, files)
        for e in rel.edges:  # generated files and their generators are what a regeneration has to recheck
            if e["kind"] == "produced_by" and split(e["target"])[0] == repo:
                subjects.update((split(e["source"])[1], split(e["target"])[1]))
        found = tests_for(fleet, repo, rev, [s for s in subjects if s in files])
        for path, test, method in found:
            rel.add("tested_by", f"{repo}:{path}", f"{repo}:{test}", f"{repo}:{test}", method=method,
                    basis="observed" if method in ("ast-import", "workflow") else "derived")
        tested = {p for p, _t, _m in found}
        rel.cover(repo, "retest", {"subjects": len(subjects), "registered": len(tested & subjects),
                                   "unregistered": sorted(subjects - tested)[:20], "unregistered_count": len(subjects - tested)})
        if "BrowserTestKit" in {split(e["source"])[0] for e in edges if split(e["target"])[0] == repo} \
                and not any(k.startswith("receipt:") for k in rel.coverage.get(repo, {})):
            rel.cover(repo, "receipt", "not_collected")  # uses the browser kit, keeps no receipt: never a success
    for consumer in (registry or {}).get("consumers", []):
        ci = consumer.get("locked_ci")
        repo = short(consumer["repository"])
        if not ci or repo not in readable:
            continue
        files = fleet.files(repo, readable[repo]["revision"])
        data = fleet.read(repo, readable[repo]["revision"], ci["workflow"]) if ci["workflow"] in files else None
        compare = "unknown" if data is None else "match" if sha256(data) == ci["sha256"] else "different"
        for path in sorted(copies.get(repo, ())):
            rel.add("tested_by", f"{repo}:{path}", f"{repo}:{ci['workflow']}", f"{PARENT}:vendor-consumers.json",
                    method="locked_ci", compare=compare)
    if snapshot:
        pr_relations(rel, snapshot, names)
    return rel.result()


# ---------------------------------------------------------------- PRs, runs and attempts (audit snapshot, gh_identity rows)

def _pr_node(record_id, names):
    match = re.fullmatch(r"(.+?)#(i?)(\d+)", str(record_id))
    if not match:
        return None
    repo = names.get(short(match.group(1)), short(match.group(1)))
    return f"{repo}:#{match.group(2)}{match.group(3)}"


def pr_relations(rel, snapshot, names, *, lock=None):
    """depends_on between PRs (repository-qualified, so equal numbers in two repositories never meet) and CI state."""
    lock = lock or f"{PARENT}:#audit@{snapshot.get('generated_at', '')}"
    for record in snapshot.get("records", []):
        if record.get("kind") != "pr":
            continue
        node = _pr_node(record["id"], names)
        state = ci_state(record.get("head_sha"), [dict(c, head_sha=record.get("head_sha")) for c in record.get("checks", [])])
        rel.cover(split(node)[0], "pr:" + split(node)[1], {"head_sha": record.get("head_sha"), "ci": state["state"]})
        for dep in record.get("depends_on") or []:
            source = _pr_node(dep, names)
            if source is None:
                rel.finding(split(node)[0], "missing-reference", record["id"], f"{record['id']} depends on {dep!r}, not a record id")
                continue
            rel.add("depends_on", source, node, lock, method="audit-snapshot", observed_at=snapshot.get("generated_at"),
                    value={"head_sha": record.get("head_sha"), "ci": state["state"]})


def _run_of(row):
    match = re.search(r"/actions/runs/(\d+)(?:/attempts/(\d+))?", str(row.get("url") or ""))
    run_id = row.get("run_id") or (int(match.group(1)) if match else None)
    attempt = row.get("attempt") or (int(match.group(2)) if match and match.group(2) else 1)
    return run_id, attempt


def ci_state(head_sha, runs):
    """CI of one head: only rows observed for that head count; every attempt is kept; a retry hides no failure.

    runs: gh_identity rows (run_id, attempt, head_sha, status, conclusion, name) or ci_status check rows (url).
    """
    current, other = [], 0
    for row in runs or []:
        if head_sha and row.get("head_sha") == head_sha:
            current.append(row)
        else:
            other += 1
    if not current:
        return {"state": "not_collected", "head_sha": head_sha, "attempts": [], "other_heads": other, "retried_after_failure": False}
    latest, attempts = {}, []
    for row in current:
        run_id, attempt = _run_of(row)
        key = (row.get("name") or row.get("workflow_id"), run_id)
        item = {"name": key[0], "run_id": run_id, "attempt": attempt, "status": row.get("status"), "conclusion": row.get("conclusion")}
        attempts.append(item)
        if key not in latest or attempt >= latest[key]["attempt"]:
            latest[key] = item
    attempts.sort(key=lambda x: (str(x["name"]), x["run_id"] or 0, x["attempt"]))
    finals = list(latest.values())
    if any(str(x["status"]).lower() not in ("completed", "none") and x["conclusion"] is None for x in finals):
        state = "running"
    elif any(str(x["conclusion"]).lower() in FAILED for x in finals):
        state = "failure"
    elif all(str(x["conclusion"]).lower() in PASSED for x in finals):
        state = "success"
    else:
        state = "unverifiable"
    failed_before = any(str(x["conclusion"]).lower() in FAILED for x in attempts if x not in finals)
    return {"state": state, "head_sha": head_sha, "attempts": attempts, "other_heads": other, "retried_after_failure": failed_before}


def compare_runs(expected, observed):
    """Expected run ids against observed result rows: a missing result is not_collected, never success."""
    seen = {}
    for row in observed or []:
        seen.setdefault(row["id"], []).append(row)
    return {"matched": sorted(x for x in expected if x in seen),
            "missing": [{"id": x, "state": "not_collected"} for x in sorted(expected) if x not in seen],
            "unexpected": sorted(x for x in seen if x not in set(expected))}


# ---------------------------------------------------------------- walking the relations

def relation_cycles(edges, *, limit=5):
    """Representative cycles among relations (reported; nothing stops on them — evidence graphs need not be DAGs)."""
    out = {}
    for e in edges:
        out.setdefault(e["source"], []).append(e["target"])
    colour, cycles = {}, []
    for start in sorted(out):
        if colour.get(start):
            continue
        stack = [(start, iter(sorted(out.get(start, ()))))]
        path, colour[start] = [start], 1
        while stack and len(cycles) < limit:
            node, children = stack[-1]
            child = next(children, None)
            if child is None:
                colour[node] = 2
                stack.pop()
                path.pop()
            elif colour.get(child) == 1:
                cycles.append(path[path.index(child):] + [child])
            elif not colour.get(child):
                colour[child] = 1
                path.append(child)
                stack.append((child, iter(sorted(out.get(child, ())))))
    return cycles
