class ShapesCyclesLimits(unittest.TestCase):
    def test_duplicate_and_missing_references_and_wrong_shapes_are_findings(self):
        class Tree:  # the minimum Fleet surface the corpus adapter reads
            def files(self, repo, rev):
                return {"c/classification.json": None, "c/cases/a.xml": None, "c/golden/a.out": None}

            def read(self, repo, rev, path):
                return b"FOUND: x\nNOT FOUND: y\nHINT: z\n"
        rel = records.Relations()
        items = [{"id": "a", "repo": "x/r", "run_id": 1, "xml": "cases/a.xml", "golden": "golden/a.out"},
                 {"id": "a", "repo": "x/r", "run_id": 2, "xml": "cases/a.xml", "golden": "golden/a.out"},
                 {"id": "b", "repo": "x/r", "run_id": 3, "xml": "cases/missing.xml"}]
        records._corpus(rel, Tree(), "lab", "r", "c/classification.json", items, {})
        result = rel.result()
        kinds = {(f["kind"], f["subject"]) for f in result["findings"]}
        self.assertIn(("duplicate-id", "c/classification.json#a"), kinds)
        self.assertIn(("missing-reference", "c/classification.json#b"), kinds)
        runs = sorted(e["source"] for e in result["relations"] if e["kind"] == "observed_in")
        self.assertEqual(runs, ["x/r:actions/runs/1", "x/r:actions/runs/2"])  # same message, two runs: two observations
        golden = next(e for e in result["relations"] if e["kind"] == "derived_from")
        self.assertEqual({k: golden["value"][k] for k in ("found", "not_found", "hint")}, {"found": 1, "not_found": 1, "hint": 1})
        wrong = [{"kind": "observed_in", "source": "lab:file.txt", "target": "lab:x.xml", "lock": "lab:c.json"}]
        self.assertEqual([f["kind"] for f in fleet.check_shapes(wrong, {"repositories": [{"repository": "lab"}]})], ["shape"])

    def test_a_handle_becomes_a_key_only_while_it_is_complete_and_unique(self):
        rows = [{"id": "a", "run": 1, "job": "x"}, {"id": "b", "run": 1, "job": None}, {"id": "c", "run": 2, "job": "x"}]
        report = records.key_report(rows, [("id",), ("run",), ("job",), ("run", "id")])
        self.assertEqual([report[k]["verdict"] for k in ("id", "run", "job", "run+id")], ["key", "collides", "incomplete", "key"])
        again = records.key_report(rows + [dict(rows[0])], [("id",)])["id"]  # the same entry listed twice
        self.assertEqual((again["verdict"], again["repeats"], again["collisions"]), ("repeat", 1, 0))
        broken = records.key_report(rows + [{"id": "a", "run": 9, "job": "y"}], [("id",)])["id"]  # one more entry demotes it
        self.assertEqual((broken["verdict"], broken["examples"]), ("collides", ["a"]))

    def test_corpus_distinguishes_repeats_from_other_ids_collisions(self):
        class EmptyFleet:
            def files(self, *_args):
                return []

        rows = [{"id": "repeat", "source_file": "same.xml"}] * 2
        for index in range(7):  # More collisions than the five displayed examples.
            rows.extend({"id": f"conflict-{index}", "source_file": source}
                        for source in ("first.xml", "second.xml"))
        rel = records.Relations()
        records._corpus(rel, EmptyFleet(), "repo", "rev", "cases.json", rows, {})
        findings = {f["subject"]: f for f in rel.findings
                    if f["kind"] in ("repeated-entry", "duplicate-id")}
        self.assertEqual(findings["cases.json#repeat"]["kind"], "repeated-entry")
        self.assertIn("identical fields", findings["cases.json#repeat"]["detail"])
        for index in range(7):
            self.assertEqual(findings[f"cases.json#conflict-{index}"]["kind"], "duplicate-id")
            self.assertIn("different fields", findings[f"cases.json#conflict-{index}"]["detail"])
        identity = rel.coverage["repo"]["corpus:cases.json"]["identity"]["id"]
        self.assertEqual((identity["repeats"], identity["collisions"]), (1, 7))

    def test_cycles_are_reported_and_the_rest_is_still_walked(self):
        relations = [{"kind": "derived_from", "source": "a:x", "target": "a:y", "lock": "a:r"},
                     {"kind": "derived_from", "source": "a:y", "target": "a:x", "lock": "a:r"},
                     {"kind": "derived_from", "source": "b:p", "target": "b:q", "lock": "b:r"}]
        self.assertEqual(records.relation_cycles(relations), [["a:x", "a:y", "a:x"]])
        graph = {"edges": [], "prefixes": {}, "evidence": {"relations": relations}}
        self.assertEqual([r["node"] for r in fleet.impact(graph, ["a:x"])["rows"]], ["a:y"])
        self.assertEqual([r["node"] for r in fleet.impact(graph, ["b:p"])["rows"]], ["b:q"])

    def test_hypotheses_are_candidates_not_reverification(self):
        relations = [{"kind": "derived_from", "source": "w:", "target": "a:receipt.json", "lock": "a:receipt.json", "basis": "hypothesis"}]
        reach = fleet.impact({"edges": [], "prefixes": {}, "evidence": {"relations": relations}}, ["w:"])
        self.assertEqual((reach["rows"], [c["node"] for c in reach["view"]["candidates"]]), ([], ["a:receipt.json"]))

    def test_output_is_deterministic_and_capped(self):
        def build(limit):
            rel = records.Relations(limit)
            for n in (3, 1, 2):
                rel.add("derived_from", f"a:in{n}", "a:out", "a:r", method="sha256")
            return rel.result()
        self.assertEqual(json.dumps(build(10)), json.dumps(build(10)))
        capped = build(2)
        self.assertEqual(([e["source"] for e in capped["relations"]], capped["dropped"]), (["a:in1", "a:in2"], 1))


