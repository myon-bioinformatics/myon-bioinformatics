    def test_a_newer_verdict_keeps_the_older_counterexamples(self):
        _f, _d, graph = self.graph()
        edge = next(e for e in graph["evidence"]["relations"] if e["kind"] == "derived_from" and e["source"].endswith("#P1"))
        self.assertEqual(edge["value"]["verdict"], "Supported")
        self.assertEqual([h["verdict"] for h in edge["value"]["history"]], ["Refuted", "Supported"])
        self.assertEqual(edge["value"]["rows_with_counterexamples"], 1)
        p2 = next(e for e in graph["evidence"]["relations"] if e["kind"] == "derived_from" and e["source"].endswith("#P2"))
        self.assertEqual(p2["state"], "pending")  # inconclusive: no supports, no contradicts
        self.assertFalse([e for e in graph["evidence"]["relations"] if e["kind"] in ("supports", "contradicts") and "#P2" in e["target"]])

    def test_receipt_layers_are_separate_checks(self):
        layers = records.receipt_layers(json.loads(receipt(GIF)), GIF, "b" * 40)
        self.assertEqual(layers, {"exists": "success", "digest": "match", "format": "success", "operation": "success",
                                  "visual": "not_collected", "commit": "different"})
        broken = b"PK" + GIF[2:]
