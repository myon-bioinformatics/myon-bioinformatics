def sha(data):
    return hashlib.sha256(data if isinstance(data, bytes) else data.encode()).hexdigest()


def judged(pid, at, data, code, verdict, counterexamples=0):
    return {"recorded_at": at, "id": pid, "definition_sha256": "d" * 64, "data_sha256": sha(data), "code_version": code,
            "objection": False, "forms": {"original": {"verdict": verdict, "n": 10, "counterexamples": counterexamples}}}


def receipt(image, **extra):
    data = {"schema": "btk-evidence-gif/2", "gif": "browser.gif", "bytes": len(image), "sha256": sha(image), "recorded": "2026-11-01",
            "commit": "a" * 40, "shots": [{"label": "home", "url": "/site/index.html", "status": "pass"}], "summary": {"pass": 1, "fail": 0}}
    data.update(extra)
    return json.dumps(data)


